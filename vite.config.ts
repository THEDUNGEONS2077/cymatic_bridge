/**
 * vite.config.ts: build, dev server and tests (Vitest) for cymatic_bridge.
 *
 * CYMATIC_BASE sets the site path: "/" locally, "/cymatic_bridge/" for
 * GitHub Pages. `@/` points at src/.
 *
 * The service-worker and preload plugins are cyberdeck_terminal's, renamed:
 * the page opens from a stored copy of the build, and the app's chunk is
 * fetched with the first files. The bridge plugin (cyberdeck's too) packs
 * the title bridge extension (bridge/) as cymatic-bridge.zip next to the
 * page, for the bar's GET TITLE BRIDGE.
 */
import react from '@vitejs/plugin-react';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

import { makeZip } from './scripts/zip.ts';

// The version (package.json) and build number (the newest CHANGELOG.md entry), shown in diagnostics and in exports.
const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8')) as { version: string };
const build = Number(/\(build (\d+)\)/.exec(readFileSync(new URL('./CHANGELOG.md', import.meta.url), 'utf8'))?.[1] ?? 0);

const base = process.env.CYMATIC_BASE ?? '/';

/**
 * Writes dist/sw.js after a build: a service worker that stores every file
 * of this build, so the page opens from this computer, not the network.
 *
 *   - The page itself is served from the store first (cyberdeck's lesson:
 *     asking the network first cost a full round trip before anything could
 *     start). Updates
 *     still arrive: on every open the browser checks sw.js itself, and a
 *     new build installs in the background and shows from the next open.
 *   - Other files (named by their content, so never stale) come from the
 *     store first too.
 *   - Installing fetches every file past the browser's HTTP cache
 *     (`cache: 'reload'`), so a new build can never store an old page.
 *   - The previous build's store is kept (only older ones are deleted), so
 *     a page still open on the old build can load the rest of its files.
 *
 * The cache name starts with the build time (so names sort oldest first)
 * and ends with a hash of the files. Its prefix is this app's own:
 * cyberdeck_terminal and quest_log_desktop live on the same origin, and
 * each app only ever deletes its own caches.
 */
function serviceWorker(): Plugin {
  // The build's output folder (dist/ unless --outDir says otherwise).
  let out = fileURLToPath(new URL('./dist', import.meta.url));
  return {
    name: 'cymatic-service-worker',
    apply: 'build',
    configResolved(config) {
      out = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const name of readdirSync(dir)) {
          const p = join(dir, name);
          if (statSync(p).isDirectory()) walk(p);
          else if (name !== 'sw.js') files.push(relative(out, p).split('\\').join('/'));
        }
      };
      walk(out);
      files.sort();
      const hash = createHash('sha256');
      for (const f of files) hash.update(f).update(readFileSync(join(out, f)));
      const version = `${new Date().toISOString().replace(/\D/g, '').slice(0, 14)}-${hash.digest('hex').slice(0, 12)}`;
      const urls = [base, ...files.filter((f) => f !== 'index.html').map((f) => `${base}${f}`)];
      writeFileSync(
        join(out, 'sw.js'),
        `// sw.js: cymatic_bridge's service worker (generated by vite.config.ts; don't edit).
// Keeps a copy of every file of this build, and serves the page from it: it opens
// without waiting for the network. A new build installs in the background (the
// browser checks this file on every open) and shows from the next open.
const PREFIX = 'cymatic_bridge-';
const CACHE = PREFIX + '${version}';
const INDEX = '${base}';
const FILES = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', (event) => {
  // Past the HTTP cache: a new build must never store an old copy of a file.
  const requests = FILES.map((url) => new Request(url, { cache: 'reload' }));
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(requests)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  // Keep this build and the one before (a page still open on it may need its files); delete older ones.
  event.waitUntil(
    caches
      .keys()
      .then((keys) => {
        const ours = keys.filter((k) => k.startsWith(PREFIX)).sort();
        const keep = new Set([CACHE, ...ours.filter((k) => k < CACHE).slice(-1)]);
        return Promise.all(ours.filter((k) => !keep.has(k)).map((k) => caches.delete(k)));
      })
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // Only this app's files: cyberdeck_terminal and quest_log_desktop share the origin and have their own workers.
  if (!new URL(request.url).pathname.startsWith(INDEX)) return;
  if (request.mode === 'navigate') {
    // The page from the store first: no network round trip before it can start.
    event.respondWith(caches.match(INDEX, { cacheName: CACHE }).then((hit) => hit || fetch(request)).catch(() => caches.match(INDEX)));
    return;
  }
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`,
      );
    },
  };
}

/**
 * Lists the app's own chunk (src/start.tsx: React, storage, the HUD)
 * in index.html as a modulepreload, so the browser fetches it with the
 * first files instead of once main.tsx has run and asked for it: on a
 * first visit that's a network round trip sooner (optimization pass 2,
 * 2026-10-22). It's still only run when main.tsx imports it, after the
 * scene has started.
 */
function preloadApp(): Plugin {
  return {
    name: 'cymatic-preload-app',
    apply: 'build',
    transformIndexHtml: {
      order: 'post',
      handler(_html, ctx) {
        const chunk = Object.values(ctx.bundle ?? {}).find((c) => c.type === 'chunk' && c.facadeModuleId?.endsWith('/src/start.tsx'));
        if (!chunk) return [];
        return [{ tag: 'link', attrs: { rel: 'modulepreload', crossorigin: true, href: `${base}${chunk.fileName}` }, injectTo: 'head' }];
      },
    },
  };
}

/** Packs every file in bridge/ inside a `cymatic-bridge/` folder (so unzipping makes one folder to load in chrome://extensions). */
function packBridge(): Buffer {
  const dir = fileURLToPath(new URL('./bridge', import.meta.url));
  const entries: { name: string; data: Buffer }[] = [];
  for (const name of readdirSync(dir).sort()) {
    if (statSync(join(dir, name)).isFile()) entries.push({ name: `cymatic-bridge/${name}`, data: readFileSync(join(dir, name)) });
  }
  return makeZip(entries);
}

/**
 * cymatic-bridge.zip next to the page: emitted as a build asset (so it's in
 * dist/ before the service worker lists the files), and served fresh by the
 * dev server too (packed on each request), so GET TITLE BRIDGE works there.
 */
function bridgeZip(): Plugin {
  return {
    name: 'cymatic-bridge-zip',
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'cymatic-bridge.zip', source: packBridge() });
    },
    configureServer(server) {
      server.middlewares.use(`${base}cymatic-bridge.zip`, (_req, res) => {
        res.setHeader('Content-Type', 'application/zip');
        res.end(packBridge());
      });
    },
  };
}

export default defineConfig({
  base,
  plugins: [react(), preloadApp(), bridgeZip(), serviceWorker()],
  define: { __APP_VERSION__: JSON.stringify(pkg.version), __APP_BUILD__: String(build) },
  resolve: { alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) } },
  // ES2022: the entry point awaits persistence before rendering (top-level await).
  build: { outDir: 'dist', sourcemap: false, target: 'es2022' },
  // The scene's worker (src/scene/worker.ts) is a module worker, bundled on its own (then inlined in the host's chunk: host.ts).
  worker: { format: 'es' },
  test: {
    globals: true,
    // Logic tests run in Node; DOM tests opt in with `// @vitest-environment jsdom`.
    environment: 'node',
    include: ['src/**/*.test.{ts,tsx}'],
  },
});
